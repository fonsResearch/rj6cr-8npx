(* Register bits per block, from the specification circuit's state interfaces. *)
open! Base
open Spec_circuit.State

let bits widths = List.fold widths ~init:0 ~f:( + )
let of_names l = bits (List.map l ~f:snd)

let () =
  let chip = Chip.to_list Chip.port_names_and_widths in
  let with_prefix p = List.filter chip ~f:(fun (n, _) -> String.is_prefix n ~prefix:p) in
  let th = of_names (Thread.to_list Thread.port_names_and_widths) in
  let rule = of_names (Rule.to_list Rule.port_names_and_widths) in
  let line = Line.to_list Line.port_names_and_widths in
  let line_group pred = of_names (List.filter line ~f:(fun (n, _) -> pred n)) in
  let is p n = String.is_prefix n ~prefix:p in
  let line_cfg = line_group (fun n -> is "lc" n || is "owner" n) in
  let line_resp = line_group (fun n -> is "resp" n || is "q_" n) in
  let line_tx = line_group (is "t_") and line_rx = line_group (is "r_") in
  let line_other = of_names line - line_cfg - line_resp - line_tx - line_rx in
  let host = of_names (Host.to_list Host.port_names_and_widths) in
  let trace = of_names (Trace.to_list Trace.port_names_and_widths) in
  let verdicts = of_names (with_prefix "fail_") + of_names (with_prefix "blame_") (* includes blame_before_fail *) in
  let total = of_names chip in
  let pads =
    of_names
      (List.filter chip ~f:(fun (n, _) ->
         List.exists [ "now"; "value"; "dir"; "owner"; "od"; "safe_val"; "safe_dir"; "filt"; "x"; "s"; "fcnt"; "pv_prev"; "oe_hist" ]
           ~f:(fun p -> String.equal n p || (String.is_prefix n ~prefix:p && String.for_all (String.drop_prefix n (String.length p)) ~f:Char.is_digit))))
  in
  let other = total - (3 * th) - (4 * rule) - of_names line - host - trace - verdicts - pads in
  let row name n = Stdio.printf "| %s | %d |\n" name n in
  Stdio.printf "<!-- generated by spec/circuit/bin/gen_state_table.exe from spec/circuit/state.ml -->\n";
  Stdio.printf "| block | register bits |\n|---|---|\n";
  row "thread (each of 3)" th;
  row "rule slot (each of 4)" rule;
  row "verdicts (fail, blame, order)" verdicts;
  row "pins: now, values, directions, owners, safe pattern, synchronisers, filters, history" pads;
  row "host port and status" (host + other);
  row "trace" trace;
  row "line unit: configuration and owner" line_cfg;
  row "line unit: response rules" line_resp;
  row "line unit: transmitter" line_tx;
  row "line unit: receiver" line_rx;
  row "line unit: other" line_other;
  row "**total**" total
;;
