"""Draw doc/spec/fig/timing_contract.png from doc/spec/fig/timing_contract.csv (the reference
model's per-cycle record, generated by spec/contract_trace.ml and kept current by `dune test`).

usage: python3 tools/plot_timing_contract.py [csv] [png]
"""
import csv
import sys

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
from matplotlib.patches import Rectangle  # noqa: E402

CSV = sys.argv[1] if len(sys.argv) > 1 else "doc/spec/fig/timing_contract.csv"
PNG = sys.argv[2] if len(sys.argv) > 2 else "doc/spec/fig/timing_contract.png"

INK, GREY, PAD, RULE, HELD = "#222222", "#8a8a8a", "#1f5f9e", "#b3661a", "#c23b3b"
BASE, SMALL, TICK = 8, 7, 6

rows = list(csv.DictReader(open(CSV, newline="")))
for r in rows:
    for k in ("cycle", "armed", "due", "t", "pad", "rule_active", "rule_count"):
        r[k] = int(r[k])


def instruction_spans(rs):
    """(first cycle, last cycle, text, waited) for each pass of an instruction through the pipeline."""
    spans, start = [], None
    for r in rs:
        if r["stage"] == "F":
            start = r["cycle"]
        elif r["stage"] in ("X", "W") and start is not None:
            spans.append((start, r["cycle"], r["instruction"], r["stage"] == "W"))
            start = None
    return spans


def step(ax, rs, key, base, height, color):
    xs, ys = [], []
    for r in rs:
        xs += [r["cycle"], r["cycle"] + 1]
        ys += [base + height * r[key]] * 2
    ax.plot(xs, ys, color=color, lw=1.4, solid_joinstyle="miter")


def panel(ax, rs, title, with_rule):
    n0, n1 = rs[0]["cycle"], rs[-1]["cycle"] + 1
    # instruction passes
    for a, b, text, waited in instruction_spans(rs):
        style = dict(ec=GREY, lw=0.8, ls=(0, (3, 2)) if waited else "-")
        ax.add_patch(Rectangle((a, 3.05), b - a + 1, 0.7, fc="white" if waited else "#eeeeee", **style))
        if not waited:
            ax.add_patch(Rectangle((b, 3.05), 1, 0.14, fc=INK, ec="none"))
        ax.text(a + 0.15, 3.45, text + (" (waits)" if waited else ""), va="center", ha="left", fontsize=TICK,
                color=INK)
    step(ax, rs, "armed", 2.0, 0.6, INK)
    step(ax, rs, "pad", 1.0, 0.6, PAD)
    if with_rule:
        top = max(r["rule_count"] for r in rs)
        xs, ys = [], []
        for r in rs:
            xs += [r["cycle"], r["cycle"] + 1]
            ys += [0.0 + 0.6 * r["rule_count"] / top] * 2
        ax.plot(xs, ys, color=RULE, lw=1.4)
        ax.plot([n0, n1], [0.6, 0.6], color=RULE, lw=0.8, ls=(0, (1, 2)))
        ax.text(n1 - 0.2, 0.66, "minimum 12", ha="right", va="bottom", fontsize=TICK, color=RULE)
    # deadlines: the cycle in which the pad shows the new level
    edges = [r["cycle"] for prev, r in zip(rs, rs[1:]) if prev["pad"] != r["pad"]]
    deadlines = sorted({r["t"] for r in rs if r["armed"]})
    for t in deadlines:
        late = t not in edges
        ax.plot([t, t], [0.95, 2.75], color=HELD if late else GREY, lw=0.8, ls=(0, (4, 2)))
        ax.text(t + 0.15, 2.82, "deadline t = %d" % t, fontsize=TICK, color=HELD if late else INK, va="bottom")
    for e in edges:
        if e not in deadlines:
            ax.text(e + 0.3, 1.36, "pad changes in cycle %d,\nt becomes %d" % (e, e), fontsize=TICK, color=HELD,
                    va="center", ha="left", linespacing=1.15)
    ax.set_xlim(n0, n1)
    ax.set_ylim(-0.15 if with_rule else 0.85, 3.95)
    ticks = [3.4, 2.3, 1.3] + ([0.3] if with_rule else [])
    names = ["thread 0\ninstruction", "commit\narmed", "pad P9"] + (["rule 0\ncount"] if with_rule else [])
    ax.set_yticks(ticks)
    ax.set_yticklabels(names, fontsize=SMALL)
    for lab, c in zip(ax.get_yticklabels(), [INK, INK, PAD, RULE]):
        lab.set_color(c)
    ax.tick_params(axis="y", length=0)
    ax.set_xticks(range(n0, n1 + 1, 4))
    ax.set_xticks(range(n0, n1 + 1), minor=True)
    ax.tick_params(axis="x", labelsize=TICK)
    for s in ("top", "right", "left"):
        ax.spines[s].set_visible(False)
    ax.set_title(title, loc="left", fontsize=BASE, color=INK)


free = [r for r in rows if r["scenario"] == "free"]
hold = [r for r in rows if r["scenario"] == "hold"]
fig, axes = plt.subplots(2, 1, figsize=(7.2, 4.6), sharex=True, gridspec_kw=dict(height_ratios=[3.1, 4.1], hspace=0.28))
panel(axes[0], free, "Pin writes are staged by the instruction and reach the pad in the deadline cycle", False)
panel(axes[1], hold, "A hold rule keeps the falling edge back until the high time reaches its minimum", True)
axes[1].set_xlabel("clock cycle (thread 0 fetches in cycles 0, 4, 8, ...; dark bar = execute cycle)", fontsize=SMALL)
fig.savefig(PNG, dpi=300, bbox_inches="tight")
